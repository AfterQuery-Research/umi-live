#!/usr/bin/env bash
# install_server.sh — stand up the GPU processing box (Lambda instance or on-prem
# NVIDIA machine) in one run. Idempotent. Portable: detects GPU vs CPU.
#
#   cp .env.example .env && $EDITOR .env      # upload token, HF repo/token
#   server/scripts/install_server.sh          # run as your login user (sudo used as needed)
#
# Brings up: Docker (+ nvidia-container-toolkit on GPU hosts), the stage images,
# the host Python env the runner needs (gripper/dataset run in-process → lerobot +
# ffmpeg), DATA_DIR, the always-up ingest container, and the runner as a systemd
# service that survives SSH logout.
set -euo pipefail

if [ "$(id -u)" -eq 0 ]; then
  echo "run as your login user (it sudo's what it needs); root would leave the" \
       "uv/venv files root-owned." >&2
  exit 1
fi
command -v apt-get >/dev/null || { echo "this installer targets Debian/Ubuntu (apt)." >&2; exit 1; }

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
USER_NAME="$(id -un)"
cd "$REPO"

[ -f "$REPO/.env" ] || { echo "no .env — copy .env.example to .env and fill it in first."; exit 1; }
set -a; . "$REPO/.env"; set +a
: "${ROBOT_UMI_UPLOAD_TOKEN:?set ROBOT_UMI_UPLOAD_TOKEN in .env (shared with the Pi)}"
export DATA_DIR="${DATA_DIR:-./data}"

echo "=== [1/8] base packages ==="
sudo apt-get update -qq
sudo apt-get install -y --no-install-recommends git curl ca-certificates ffmpeg

echo "=== [2/8] Docker ==="
if ! command -v docker >/dev/null; then
  echo "installing Docker via get.docker.com ..."
  curl -fsSL https://get.docker.com | sudo sh
fi
if ! id -nG "$USER_NAME" | tr ' ' '\n' | grep -qx docker; then
  sudo usermod -aG docker "$USER_NAME"
  echo "added $USER_NAME to the docker group — you may need to re-login for the rest to run."
fi
sudo systemctl enable --now docker
DOCKER="sudo docker"  # use sudo until the group membership takes effect this session
docker info >/dev/null 2>&1 && DOCKER="docker"
# Hosts with a PRE-installed docker (cloud images) often lack the compose v2 plugin —
# get.docker.com bundles it, but that path was skipped above. Install the plugin
# binary system-wide (so `sudo docker compose` finds it too, not just $HOME).
if ! $DOCKER compose version >/dev/null 2>&1; then
  echo "docker compose plugin missing — installing v2 plugin binary ..."
  ARCH=$(uname -m); case "$ARCH" in aarch64) ARCH=aarch64;; *) ARCH=x86_64;; esac
  sudo mkdir -p /usr/local/lib/docker/cli-plugins
  sudo curl -fsSL "https://github.com/docker/compose/releases/latest/download/docker-compose-linux-$ARCH" \
    -o /usr/local/lib/docker/cli-plugins/docker-compose
  sudo chmod +x /usr/local/lib/docker/cli-plugins/docker-compose
  $DOCKER compose version >/dev/null 2>&1 || { echo "compose plugin install failed" >&2; exit 1; }
fi
# The compose file runs umi-ingest as the HOST user so uploaded episodes land
# owned by you, not root — otherwise the runner's pair stage can't relocate the
# paired sources out of raw_episodes/ and re-merges the same session forever.
grep -q '^HOST_UID=' "$REPO/.env" || echo "HOST_UID=$(id -u)" >> "$REPO/.env"
grep -q '^HOST_GID=' "$REPO/.env" || echo "HOST_GID=$(id -g)" >> "$REPO/.env"

echo "=== [3/8] GPU detection ==="
GPU=0
if command -v nvidia-smi >/dev/null && nvidia-smi -L >/dev/null 2>&1; then
  GPU=1
  echo "GPU: $(nvidia-smi -L | head -1)"
  # A stale CPU override (from a prior CPU provisioning) would force CPU SLAM here.
  rm -f "$REPO/docker-compose.override.yml"
  # Cheap probe first (no image pull): is the nvidia docker runtime wired up?
  if ! docker info --format '{{json .Runtimes}}' 2>/dev/null | grep -q nvidia; then
    echo "installing nvidia-container-toolkit ..."
    curl -fsSL https://nvidia.github.io/libnvidia-container/gpgkey \
      | sudo gpg --dearmor --yes -o /usr/share/keyrings/nvidia-container-toolkit-keyring.gpg
    curl -fsSL https://nvidia.github.io/libnvidia-container/stable/deb/nvidia-container-toolkit.list \
      | sed 's#deb https://#deb [signed-by=/usr/share/keyrings/nvidia-container-toolkit-keyring.gpg] https://#' \
      | sudo tee /etc/apt/sources.list.d/nvidia-container-toolkit.list >/dev/null
    sudo apt-get update -qq && sudo apt-get install -y nvidia-container-toolkit
    sudo nvidia-ctk runtime configure --runtime=docker && sudo systemctl restart docker
  fi
else
  echo "no GPU detected — CPU mode (GLIM CPU build; slower). Writing docker-compose.override.yml."
  cat > "$REPO/docker-compose.override.yml" <<'YAML'
# Auto-generated by install_server.sh on a CPU host: build GLIM from the CPU base
# and drop the nvidia device reservation. Gitignored; delete on a GPU host.
services:
  umi-glim:
    build:
      args:
        BASE_IMAGE: koide3/glim_ros2:jazzy
    deploy: !reset {}
YAML
  # The `!reset` merge tag needs Docker Compose >= 2.24.4; older plugins choke on
  # EVERY compose command once the override exists. Validate before proceeding.
  if ! $DOCKER compose config -q >/dev/null 2>&1; then
    echo "ERROR: your docker compose is too old for the CPU override's '!reset' tag" >&2
    echo "(need >= 2.24.4; you have: $($DOCKER compose version --short 2>/dev/null))." >&2
    echo "Upgrade the compose plugin, or hand-edit docker-compose.yml to drop the" >&2
    echo "umi-glim 'deploy:' block and set its BASE_IMAGE to koide3/glim_ros2:jazzy." >&2
    rm -f "$REPO/docker-compose.override.yml"
    exit 1
  fi
fi

echo "=== [4/8] host Python env for the runner (in-process gripper + dataset) ==="
if ! command -v uv >/dev/null && [ ! -x "$HOME/.local/bin/uv" ]; then
  curl -LsSf https://astral.sh/uv/install.sh | sh
fi
export PATH="$HOME/.local/bin:$PATH"
# --frozen: keep uv.lock authoritative (match the ingest image) so the runner's
# in-process gripper/dataset deps don't drift from the container versions.
uv sync --frozen --no-dev --package robot-umi-server
# Bimanual align stage (rig.alignment / --pair pipelines) lazily imports open3d +
# gtsam — the server's [align] extra. It is NOT in the base sync; without it every
# bimanual episode fails at align() with "No module named 'open3d'". gtsam needs
# the 4.3 prerelease for numpy>=2 (stable 4.2.1 pins numpy<2 and segfaults).
uv pip install --python "$REPO/.venv/bin/python" --prerelease=allow "open3d>=0.18" "gtsam>=4.3a0"

echo "=== [5/8] build stage images ==="
$DOCKER compose build umi-ingest
$DOCKER compose --profile stages build

echo "=== [6/8] DATA_DIR ==="
mkdir -p "$DATA_DIR/raw_episodes" "$DATA_DIR/derived"
echo "DATA_DIR = $(cd "$DATA_DIR" && pwd)"

echo "=== [7/8] start ingest (always-up) ==="
$DOCKER compose up -d umi-ingest

echo "=== [8/8] runner systemd service ==="
sed -e "s#@REPO@#$REPO#g" -e "s#@USER@#$USER_NAME#g" \
    "$REPO/config/systemd/umi-runner.service" | sudo tee /etc/systemd/system/umi-runner.service >/dev/null
sudo systemctl daemon-reload
sudo systemctl enable --now umi-runner

# --- self-test -----------------------------------------------------------------
echo
echo "=== self-test ==="
fail=0
sleep 3
# A bare POST returns 401/400 when up; curl prints 000 on connection-refused. Do
# NOT use -f here: it makes curl exit non-zero AND still print the code, which the
# old `|| echo down` fallback then concatenated ("000down") and misread as "up".
code=$(curl -sS -o /dev/null -w '%{http_code}' -X POST "http://127.0.0.1:8080/upload" 2>/dev/null || echo 000)
case "$code" in
  000) echo "FAIL ingest not reachable on :8080"; fail=1 ;;
  *)   echo "OK  ingest up (HTTP $code)" ;;
esac
systemctl is-active --quiet umi-runner && echo "OK  runner service active" || { echo "FAIL runner not active — journalctl -u umi-runner"; fail=1; }
for img in umi-ingest umi-decode umi-slam umi-dataset; do
  $DOCKER image inspect "$img" >/dev/null 2>&1 && echo "OK  image $img built" || { echo "FAIL image $img missing"; fail=1; }
done
[ "$GPU" = "1" ] && echo "GPU mode." || echo "CPU mode (see docker-compose.override.yml)."

echo
if [ "$fail" = "0" ]; then
  echo "server up. Point the Pis here: ./provision_pi.sh --target gpu <user@pi> with"
  echo "SERVER_URL (LAN box) or SERVER_SSH=$USER_NAME@<this-box> (cloud box, only :22 open"
  echo "— installs a boot-persistent Pi->box tunnel) in the rig env."
  echo "Bimanual (two-Pi) rigs: set ROBOT_UMI_RUNNER_ARGS=--pair in .env and restart"
  echo "umi-runner so the runner merges leader+follower episodes into one 12-D dataset."
else
  echo "install finished with FAILUREs above."; exit 1
fi
